#!/usr/bin/env bash
set -Eeuo pipefail
umask 077
ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
PROFILE_NAME="${XLX_RUNTIME_PROFILE:-}"
DASH="${XLX_DASHBOARD_DIR:-/var/www/html/xlxd}"
[ "$PROFILE_NAME" = "xlx026-prod-20261017" ] || { echo "unsupported runtime profile: $PROFILE_NAME" >&2; exit 2; }
PROFILE="$ROOT/profiles/$PROFILE_NAME"
[ -d "$PROFILE/dashboard-overlay" ] || { echo "profile overlay missing" >&2; exit 1; }

# This is a recovery overlay, not a replacement for generic installation.
# It intentionally contains no credentials, private keys, databases, logs or production backups.
cp -a "$PROFILE/dashboard-overlay/." "$DASH/"
# Remove only explicitly listed generic files that are absent from the captured XLX026 webroot.
# No wildcard or recursive deletion is allowed here.
while IFS= read -r rel; do
  [ -n "$rel" ] || continue
  case "$rel" in /*|*..*) echo "invalid recovery removal path: $rel" >&2; exit 23;; esac
  rm -f -- "$DASH/$rel"
done < "$PROFILE/REMOVE_GENERIC_PATHS.txt"
rmdir "$DASH/i18n/locales" "$DASH/i18n" "$DASH/lib" 2>/dev/null || true
if [ -n "${XLX_ADMIN_SLUG:-}" ] && [ -f "$PROFILE/control/index.php" ]; then
  install -d -m 0750 "$DASH/$XLX_ADMIN_SLUG"
  install -m 0640 "$PROFILE/control/index.php" "$DASH/$XLX_ADMIN_SLUG/index.php"
fi
# Overlay files are public code/assets and remain root-owned/readable. Do not chmod/chown
# the whole webroot: generated configs may contain hashes/secrets with stricter modes.
while IFS= read -r -d '' src; do
  rel="${src#"$PROFILE/dashboard-overlay/"}"
  dst="$DASH/$rel"
  [ -f "$dst" ] && chmod 0644 "$dst"
done < <(find "$PROFILE/dashboard-overlay" -type f -print0)
[ -z "${XLX_ADMIN_SLUG:-}" ] || { chown root:www-data "$DASH/$XLX_ADMIN_SLUG/index.php"; chmod 0640 "$DASH/$XLX_ADMIN_SLUG/index.php"; }

# Add only the extra edge routes required by the captured Live Hub/V2 runtime.
# The generic Nginx template, domain, TLS and private admin slug stay generated by modules/70-nginx.sh.
if [ -f /etc/nginx/sites-available/xlx-modern.conf ]; then
  install -d -m 0755 /etc/nginx/snippets
  install -m 0644 "$PROFILE/runtime/nginx/xlx026-live-runtime.conf" /etc/nginx/snippets/xlx026-live-runtime.conf
  python3 - /etc/nginx/sites-available/xlx-modern.conf <<'PY'
from pathlib import Path
import sys
p=Path(sys.argv[1]); s=p.read_text()
inc='    include /etc/nginx/snippets/xlx026-live-runtime.conf;' + chr(10)
if inc not in s:
    out=[]
    for line in s.splitlines(True):
        out.append(line)
        if line.lstrip().startswith('root '): out.append(inc)
    p.write_text(''.join(out))
PY
  nginx -t
  systemctl reload nginx
fi

if [ "${XLX_PROFILE_DASHBOARD_ONLY:-0}" = "1" ]; then
  echo "profile_dashboard_overlay=APPLIED"
  exit 0
fi

# Rebuild the exact approved XLXD 2.5.3 + TOT180 + TX Turn Guard candidate.
# This runs only on a fresh full install with the explicit XLX026 recovery profile.
work="$(mktemp -d /tmp/xlx026-profile-xlxd.XXXXXX)"
trap 'rm -rf "$work"' EXIT
git clone -q https://github.com/PP5PK/xlxd.git "$work/xlxd"
git -C "$work/xlxd" checkout -q e69f2dcdd9cf004d5ad199f85c27f1fa1e7e5004
bash "$ROOT/experimental/tx-turn-guard/apply-and-build.sh" "$work/xlxd" >/tmp/xlx026-profile-xlxd-build.log
xlxd_sha="$(sha256sum "$work/xlxd/src/xlxd" | awk '{print $1}')"
[ "$xlxd_sha" = "9dce43475fed2fa464e8b76f1363167827b5cb80e33981523d2e701ea3d0b9f0" ] || {
  echo "XLXD recovery build hash mismatch: $xlxd_sha" >&2
  exit 31
}
install -m 0755 "$work/xlxd/src/xlxd" /xlxd/xlxd

# Reinstall the versioned non-secret runtime sources/services used by the live panel.
install -d -m 0755 /opt/xlx026-live-hub /opt/xlx026_health_monitor /opt/xlx-modern-transmission-analyzer
install -m 0644 "$PROFILE/runtime/live-hub/server.js" /opt/xlx026-live-hub/server.js
install -m 0644 "$PROFILE/runtime/live-hub/tx-turn-state.js" /opt/xlx026-live-hub/tx-turn-state.js
install -m 0755 "$PROFILE/runtime/health-monitor/health_monitor.py" /opt/xlx026_health_monitor/health_monitor.py
install -m 0755 "$PROFILE/runtime/transmission-analyzer/monitor.py" /opt/xlx-modern-transmission-analyzer/monitor.py
install -m 0755 "$PROFILE/runtime/xlx-tx-turn-ai-monitor.py" /usr/local/lib/xlx-modern/xlx-tx-turn-ai-monitor.py

# Live Core V2 is reproducibly rebuilt from its pinned Cargo.lock on the target.
if ! command -v cargo >/dev/null 2>&1; then
  apt-get update -y
  DEBIAN_FRONTEND=noninteractive apt-get install -y cargo rustc
fi
if ! command -v node >/dev/null 2>&1; then
  apt-get update -y
  DEBIAN_FRONTEND=noninteractive apt-get install -y nodejs
fi
rm -rf /opt/xlx026-live-core-v2
cp -a "$PROFILE/runtime/live-core-v2" /opt/xlx026-live-core-v2
( cd /opt/xlx026-live-core-v2 && cargo build --release --locked )
install -m 0755 /opt/xlx026-live-core-v2/target/release/xlx026-live-core-v2 /usr/local/bin/xlx026-live-core-v2

# Install only services that do not embed secrets or the old VPS address.
install -m 0644 "$PROFILE/runtime/systemd/xlxd.service.d__tx-turn-wait.conf" /etc/systemd/system/xlxd.service.d/tx-turn-wait.conf
for unit in xlx026-live-core-v2.service xlx026-live-hub.service xlx026-health-monitor.service xlx-modern-transmission-analyzer.service xlx-tx-turn-ai-monitor.service xlx-tx-turn-ai-monitor.timer; do
  install -m 0644 "$PROFILE/runtime/systemd/$unit" "/etc/systemd/system/$unit"
done
systemctl daemon-reload
systemctl enable --now xlx026-live-core-v2.service xlx026-live-hub.service xlx026-health-monitor.service xlx-modern-transmission-analyzer.service xlx-tx-turn-ai-monitor.timer
systemctl restart xlxd.service

# xuvd/Helix exact production binaries are deliberately NOT copied from production into public Git.
# Their source/hash/provenance are retained in this profile; recovery must build/validate them via the documented gate.
echo "profile_runtime=APPLIED_NONSECRET"
echo "profile_xuvd_helix=REQUIRES_PROVENANCE_GATE"
